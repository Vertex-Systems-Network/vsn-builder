import assert from 'node:assert/strict';
import fs from 'node:fs';
import { VSN_BASELINE } from '../app/config/baseline.js';
import { normalizeResponsiveBreakpoints, createCustomBreakpoint, breakpointMediaQuery, responsiveInheritanceOrder, buildFluidClamp, containerQueryCondition, scanResponsiveIssues } from '../app/builder/responsiveEngine.js';
import { buildResponsiveTreeCss } from '../app/builder/stylePipeline.js';

const checks=[]; const check=(name,fn)=>{try{fn();checks.push([name,true]);}catch(e){checks.push([name,false,e.message]);}};
const legacy={mobileBreakpoint:749,tabletBreakpoint:989};
const bps=normalizeResponsiveBreakpoints(legacy);
check('Phase 5 baseline remains compatible',()=>assert.ok(VSN_BASELINE.phase>=5&&VSN_BASELINE.schema.responsive===2));
check('Legacy three breakpoints preserved',()=>assert.ok(['desktop','tablet','mobile'].every(id=>bps.some(x=>x.id===id))));
const custom=createCustomBreakpoint(bps,{label:'Laptop',minWidth:990,maxWidth:1199,previewWidth:1180});
check('Custom named breakpoint created',()=>assert.ok(custom.some(x=>x.id==='laptop')));
check('Breakpoint media query supports min/max',()=>assert.equal(breakpointMediaQuery({minWidth:990,maxWidth:1199}),'(min-width: 990px) and (max-width: 1199px)'));
check('Inheritance order is deterministic',()=>assert.ok(responsiveInheritanceOrder(custom,'mobile').includes('desktop')));
check('Fluid clamp generator works',()=>assert.match(buildFluidClamp({min:16,max:32,minViewport:320,maxViewport:1440}),/^clamp\(/));
check('Container query condition works',()=>assert.equal(containerQueryCondition({enabled:true,minWidth:500,maxWidth:900}),'(min-width: 500px) and (max-width: 900px)'));
const node={id:'x',type:'button',label:'Button',styles:{size:{width:'900px',height:'32px'}},responsive:{laptop:{styles:{size:{width:'700px'}},props:{}}},responsiveContainer:{enabled:true,name:'card',type:'inline-size'},containerQuery:{enabled:true,name:'card',minWidth:500,maxWidth:900,styles:{typography:{fontSize:'20px'}},props:{}}};
const css=buildResponsiveTreeCss([node],{breakpoints:custom});
check('Responsive CSS emits named media queries',()=>assert.match(css,/min-width: 990px/));
check('Responsive CSS emits container type',()=>assert.match(css,/container-type/));
check('Responsive CSS emits @container',()=>assert.match(css,/@container/));
const issues=scanResponsiveIssues([node],custom);
check('Responsive scanner detects fixed width',()=>assert.ok(issues.some(x=>x.code==='fixed-width')));
check('Responsive scanner detects tap target',()=>assert.ok(issues.some(x=>x.code==='tap-target')));
const advanced=fs.readFileSync('app/components/editor/AdvancedBuilderControls.jsx','utf8');
check('Breakpoint UI supports named breakpoints',()=>assert.match(advanced,/Responsive Breakpoints 2\.0/));
check('Breakpoint UI supports Add named breakpoint',()=>assert.match(advanced,/Add named breakpoint/));
check('Responsive panel exposes inheritance source',()=>assert.match(advanced,/Inherited from|inherit/i));
check('Responsive panel exposes fluid clamp',()=>assert.match(advanced,/Fluid|clamp/i));
check('Responsive panel exposes container queries',()=>assert.match(advanced,/query container|Container Quer/i));
const toolbar=fs.readFileSync('app/components/editor/EditorToolbar.jsx','utf8');
check('Toolbar has custom preview width',()=>assert.match(toolbar,/previewWidth/));
const canvas=fs.readFileSync('app/components/editor/Canvas.jsx','utf8');
check('Canvas has drag-resize handle',()=>assert.match(canvas,/vsn-canvas-resize-handle/));
const qa=fs.readFileSync('app/components/editor/TemplateQAPanel.jsx','utf8');
check('QA uses responsive scanner',()=>assert.match(qa,/scanResponsiveIssues/));
const migrations=fs.readFileSync('app/builder/schemaMigrations.js','utf8');
check('Migration stamps responsive schema',()=>assert.match(migrations,/responsiveSchemaVersion/));

for(const [n,ok,msg] of checks) console.log(`${ok?'PASS':'FAIL'} ${n}${msg?`: ${msg}`:''}`);
const failed=checks.filter(x=>!x[1]);
console.log(`Phase 5 Responsive audit: ${checks.length-failed.length}/${checks.length} PASS`);
if(failed.length) process.exit(1);
