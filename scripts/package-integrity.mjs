const errors = [];
for (const file of required) {
  if (!fs.existsSync(file)) errors.push(`Missing required release file: ${file}`);
  else if (fs.statSync(file).isFile() && fs.statSync(file).size === 0) errors.push(`Required file is empty: ${file}`);
}

const migrationDir = "prisma/migrations";
if (!fs.existsSync(migrationDir) || !fs.readdirSync(migrationDir).some((name) => fs.existsSync(path.join(migrationDir, name, "migration.sql")))) {
  errors.push("No Prisma migration.sql files were packaged.");
}

const sqliteCandidates = ["prisma/dev.sqlite", "prisma/dev.db", "dev.sqlite"].filter((file) => fs.existsSync(file));
for (const file of sqliteCandidates) {
  if (fs.statSync(file).size < 4096) errors.push(`Packaged SQLite baseline looks invalid: ${file}`);
}

const packageJson = JSON.parse(fs.readFileSync("package.json", "utf8"));
const packageLock = JSON.parse(fs.readFileSync("package-lock.json", "utf8"));
const baseline = JSON.parse(fs.readFileSync("BASELINE.json", "utf8"));
if (String(packageJson.version) !== String(baseline.version)) errors.push(`Package version ${packageJson.version} does not match BASELINE.json ${baseline.version}.`);
if (String(packageLock.version) !== String(packageJson.version) || String(packageLock.packages?.[""]?.version) !== String(packageJson.version)) errors.push(`package-lock.json version does not match package.json ${packageJson.version}.`);

if (errors.length) {
  console.error("VSN package integrity: FAIL");
  for (const error of errors) console.error(`- ${error}`);
  process.exit(1);
}
console.log(`VSN package integrity: PASS (${required.length} required files, ${sqliteCandidates.length} SQLite baseline file(s))`);
