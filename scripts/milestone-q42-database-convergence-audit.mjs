import fs from "node:fs";
import path from "node:path";
import { resolveScriptDatabaseLocation } from "./lib/database-location.mjs";

const read=(file)=>fs.readFileSync(file,"utf8");
let total=0, failed=0;
const check=(name,ok,detail="")=>{total++; console.log(`${ok?"PASS":"FAIL"} ${name}${detail?` · ${detail}`:""}`); if(!ok) failed++;};
const pkg=JSON.parse(read("package.json"));
const baseline=JSON.parse(read("BASELINE.json"));
const runtime=read("app/config/baseline.js");
const schema=read("prisma/schema.prisma");
const db=read("app/db.server.js");
const appLocation=read("app/utils/database-location.server.js");
const cliLocation=read("scripts/lib/database-location.mjs");
const processHelper=read("scripts/lib/prisma-process.mjs");
const prepare=read("scripts/prepare-database.mjs");
const reconcile=read("scripts/reconcile-email-builder-migration.mjs");
const health=read("app/services/database-health.server.js");
const checkScript=read("scripts/database-schema-check.mjs");
const migration=path.join("prisma","migrations","20260808234540_milestone_n1_email_builder","migration.sql");

check("Q4.2+ version lineage",baseline.version===pkg.version&&runtime.includes(`version: "${pkg.version}"`)&&runtime.includes('milestone: "Q.'));
check("Prisma schema uses explicit DATABASE_URL contract",schema.includes('url      = env("DATABASE_URL")'));
check("Runtime normalizes database location",db.includes("resolveVsnDatabaseLocation")&&db.includes("datasources")&&db.includes("VSN_DATABASE_LOCATION.url"));
check("Runtime forces normalized DATABASE_URL",db.includes("process.env.DATABASE_URL = VSN_DATABASE_LOCATION.url"));
check("App location uses schema-relative SQLite semantics",appLocation.includes('path.resolve(projectRoot, "prisma", raw)'));
check("CLI location uses schema-relative SQLite semantics",cliLocation.includes('path.resolve(projectRoot, "prisma", raw)'));
const defaultLoc=resolveScriptDatabaseLocation({cwd:process.cwd(),env:{}});
check("Default CLI DB is package prisma/dev.sqlite",defaultLoc.file===path.resolve("prisma","dev.sqlite"),defaultLoc.file);
const ciLoc=resolveScriptDatabaseLocation({cwd:process.cwd(),env:{DATABASE_URL:"file:./ci.sqlite"}});
check("Relative DATABASE_URL resolves beside schema",ciLoc.file===path.resolve("prisma","ci.sqlite"),ciLoc.file);
check("runPrisma injects normalized DATABASE_URL",processHelper.includes("withResolvedDatabaseEnv")&&processHelper.includes("env,"));
check("npm prisma command uses tested proxy",String(pkg.scripts?.prisma||"").includes("prisma-cli-proxy.mjs"));
check("Prepare has seven convergence stages",prepare.includes("${index + 1}/${stages.length}")&&prepare.includes("Email Builder migration reconciliation (pre-deploy)")&&prepare.includes("Email Builder migration reconciliation (post-deploy)"));
check("Prepare reports database target",prepare.includes("getPrismaDatabaseDiagnostics")&&prepare.includes("Database target:"));
check("N1 migration remains packaged",fs.existsSync(migration));
check("Reconciler verifies 13 Email columns",(reconcile.match(/"id", "shop", "name"/)||[]).length===1&&reconcile.includes('"deletedAt"'));
