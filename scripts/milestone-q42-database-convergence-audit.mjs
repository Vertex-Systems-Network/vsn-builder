check("Partial table auto-repair is refused",reconcile.includes("exists but is partial")&&reconcile.includes("Refusing destructive auto-repair"));
check("Schema health records actual DB file",health.includes("PRAGMA database_list")&&health.includes("databaseTargetMatches")&&health.includes("expectedDatabaseFile"));
check("Schema check prints actual/expected DB path",checkScript.includes("Runtime database:")&&checkScript.includes("Expected database:"));
